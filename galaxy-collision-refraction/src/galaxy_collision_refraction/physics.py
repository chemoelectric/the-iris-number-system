"""Physics engine for galaxy collision simulation governed by wave refraction theory.

Gravity is not a fundamental force. It is not “curvature of the fabric of space-time”.
It is classical wave refraction.

In the Unified Field Theory, all matter consists of localized concentrations of
electromagnetic wave energy (matter knots). Galaxies are extended clouds of
energy density in the universal electromagnetic field that establish an inhomogeneous
refractive index gradient:

    n(r) = 1 + (2 / c^2) * Phi(r)

where Phi(r) is the potential generated by the total energy density distribution.
The speed of electromagnetic influences is v(r) = c / n(r).
Each circulating matter knot (star) is steered by the differential wave speed
across its finite diameter:

    a = - (c^2 / (2 * n)) * grad(n) ~= - grad(Phi)
"""

